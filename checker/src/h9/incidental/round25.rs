pub(super) fn part(rec: usize) -> Part {
    let s = SAMPLES.iter().find(|s| s.rec == rec).expect("sample");
    let f = s.fields.map(f32::from_bits);
    let r = kit::rec(s.kind, [f[0], f[1], f[2]], [f[3], f[4], f[5]], f[6], f[7]);
    let coords: Vec<f32> = s
        .indices
        .iter()
        .flat_map(|&i| s.vertices[i].map(f32::from_bits))
        .collect();
    let bytes: Vec<u8> = coords.iter().flat_map(|c| c.to_le_bytes()).collect();
    assert_eq!(
        crate::sha256::hex(&bytes),
        s.sha256,
        "record {rec}: exact written mesh"
    );
    let p = kit::part_with_mesh(rec, &r, &coords);
    assert!(p.is_valid(), "record {rec}: {:?}", p.invalid);
    p
}
