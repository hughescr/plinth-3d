//! Make, or check, every committed "use as drawn" fixture in `corpus/as-drawn/`
//! from its recipe `corpus/as-drawn/sources.tsv`.
//!
//! ```text
//! cargo run --profile gate --offline -p plinth-mesh --example as_drawn_corpus            # write
//! cargo run --profile gate --offline -p plinth-mesh --example as_drawn_corpus -- --check # verify only
//! ```
//!
//! Owner, 2026-10-02: the test set uses his orientation choices, and git keeps
//! no Finder tag, so the repository marks a model with an empty `<stem>.asdrawn`
//! file beside its STL. A provisioned `corpus/models/*.stl` is gitignored and
//! not the repository's to edit, so a model the owner wants used as drawn is
//! committed here as a copy: turned 180 degrees about X when the source is
//! drawn the other way up (`turn` = `x180`, by `plinth_mesh::turn_binary_stl_x180`,
//! exact by construction), or byte for byte (`none`).
//!
//! For each row it reads the source and refuses one whose sha256 is not the
//! recorded one; turns it; refuses a result whose sha256 is not the recorded
//! one (a `-` there means "not recorded yet": the hash is printed for the
//! recipe, and the file is written). Write mode writes `<stem>.stl` and an
//! empty `<stem>.asdrawn`. `--check` writes nothing and fails unless every
//! committed file is the regenerated bytes and every marker is present and
//! empty. Either mode fails on an STL in the folder that has no row.
//! `plinth-orient`'s `as_drawn_corpus` tests make the same check under
//! `cargo test`.
//!
//! An EXAMPLE, not a test, for the reason `export_fixture` gives: it writes
//! files outside a test's own scratch.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use sha2::{Digest, Sha256};

struct Row {
    stem: String,
    source: String,
    x180: bool,
    source_sha256: String,
    result_sha256: String,
}

fn parse(text: &str) -> Result<Vec<Row>, String> {
    text.lines()
        .filter(|line| !line.trim().is_empty() && !line.starts_with('#'))
        .map(|line| {
            let fields: Vec<&str> = line.split('\t').collect();
            let [stem, source, turn, source_sha256, result_sha256] = fields.as_slice() else {
                return Err(format!("not five tab-separated fields: {line:?}"));
            };
            let x180 = match *turn {
                "x180" => true,
                "none" => false,
                other => return Err(format!("{stem}: unknown turn {other:?}")),
            };
            Ok(Row {
                stem: (*stem).to_owned(),
                source: (*source).to_owned(),
                x180,
                source_sha256: (*source_sha256).to_owned(),
                result_sha256: (*result_sha256).to_owned(),
            })
        })
        .collect()
}

fn sha256_hex(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

fn run(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let dir = root.join("corpus/as-drawn");
    let recipe = dir.join("sources.tsv");
    let text = std::fs::read_to_string(&recipe)
        .map_err(|error| format!("cannot read {}: {error}", recipe.display()))?;
    let rows = parse(&text).map_err(|problem| format!("{}: {problem}", recipe.display()))?;

    let listed: BTreeSet<&str> = rows.iter().map(|row| row.stem.as_str()).collect();
    if listed.len() != rows.len() {
        return Err(format!("{}: a stem is listed twice", recipe.display()));
    }
    let entries = std::fs::read_dir(&dir)
        .map_err(|error| format!("cannot list {}: {error}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|error| error.to_string())?.path();
        if path.extension().and_then(|ext| ext.to_str()) == Some("stl") {
            let stem = path.file_stem().map(|stem| stem.to_string_lossy().into_owned());
            if !stem.as_deref().is_some_and(|stem| listed.contains(stem)) {
                return Err(format!("{} has no sources.tsv row", path.display()));
            }
        }
    }

    let mut problems = Vec::new();
    for row in &rows {
        let source = root.join(&row.source);
        let mut bytes = std::fs::read(&source).map_err(|error| {
            format!(
                "{}: cannot read {}: {error} (provision corpus/models first: docs/development.md)",
                row.stem,
                source.display()
            )
        })?;
        let source_sha = sha256_hex(&bytes);
        if source_sha != row.source_sha256 {
            return Err(format!(
                "{}: source {} has sha256 {source_sha}, sources.tsv records {}",
                row.stem,
                source.display(),
                row.source_sha256
            ));
        }
        let facets = if row.x180 {
            plinth_mesh::turn_binary_stl_x180(&source, &mut bytes)
                .map_err(|error| format!("{}: {error}", row.stem))?
        } else {
            0
        };
        let result_sha = sha256_hex(&bytes);
        if row.result_sha256 != "-" && result_sha != row.result_sha256 {
            return Err(format!(
                "{}: the turned source has sha256 {result_sha}, sources.tsv records {}",
                row.stem, row.result_sha256
            ));
        }
        let target: PathBuf = dir.join(format!("{}.stl", row.stem));
        let marker: PathBuf = dir.join(format!("{}.asdrawn", row.stem));
        if check {
            match std::fs::read(&target) {
                Ok(committed) if committed == bytes => {}
                Ok(_) => problems.push(format!("{}: differs from the regenerated bytes", target.display())),
                Err(error) => problems.push(format!("{}: {error}", target.display())),
            }
            match std::fs::read(&marker) {
                Ok(content) if content.is_empty() => {}
                Ok(_) => problems.push(format!("{}: the marker must be empty", marker.display())),
                Err(error) => problems.push(format!("{}: {error}", marker.display())),
            }
            if row.result_sha256 == "-" {
                problems.push(format!("{}: result_sha256 not recorded", row.stem));
            }
        } else {
            std::fs::write(&target, &bytes)
                .map_err(|error| format!("cannot write {}: {error}", target.display()))?;
            std::fs::write(&marker, b"")
                .map_err(|error| format!("cannot write {}: {error}", marker.display()))?;
        }
        println!(
            "{}\t{}\t{}\tsource {source_sha}\tresult {result_sha}{}",
            row.stem,
            if row.x180 { "x180" } else { "none" },
            if row.x180 { format!("{facets} facets turned") } else { "byte copy".to_owned() },
            if row.result_sha256 == "-" { "\t(NOT RECORDED: add it to sources.tsv)" } else { "" },
        );
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems.join("\n"))
    }
}

fn main() -> ExitCode {
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    let check = match arguments.as_slice() {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => {
            eprintln!("usage: as_drawn_corpus [--check]");
            return ExitCode::from(2);
        }
    };
    match run(check) {
        Ok(()) => {
            println!(
                "as-drawn corpus {}",
                if check { "checked: every file is its recipe's bytes" } else { "written" }
            );
            ExitCode::SUCCESS
        }
        Err(problem) => {
            eprintln!("as-drawn corpus failed: {problem}");
            ExitCode::FAILURE
        }
    }
}
